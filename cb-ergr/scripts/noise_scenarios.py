#!/usr/bin/env python3
"""Literature-based noise scenarios (Step B of the 8 Nov 2026 request): derives the dB offsets from published formulas and writes
configs/scn-*.txt. Run it once; the values are then frozen in the configs (do not re-derive them after seeing results).

Background = the link model's own ambient noise at the 20 kHz carrier: Stojanovic/Wenz with shipping activity s = 0.5 and wind 5 m/s
(params::phy), the same function as AcousticLinkModel::NoisePsdDb.

(a) burst = rain squall.  Ma & Nystuen (2005, J. Atmos. Oceanic Technol. 22, 1225-1248), as quoted in search results: rain rate
    RR = 10^((SPL5k - 42.4)/15.4), SPL5k in dB re 1 uPa^2/Hz at 5 kHz, i.e. SPL5k = 42.4 + 15.4 log10(RR). Nystuen, McGlothin & Cook (1993, JASA 93,
    3169-3177): in heavy rain the sound level rises with the rain rate at all frequencies 4-21 kHz and rain is louder than wind-generated sound
    around 10 kHz. Chosen rain rate 10 mm/h ("heavy rain" begins at 7.6 mm/h). The 5 kHz excess over the background is ASSUMED to hold in the
    10-30 kHz modem band (no 20 kHz number was retrievable): excess = 10 log10(1 + 10^((SPL5k - B(5 kHz))/10)).
(b) shipping lane.  Stojanovic (2006) / Wenz (1962) shipping term N_s = 40 + 20 (s - 0.5) + 26 log f - 60 log(f + 0.03) (f in kHz): the lane is
    s = 1 (heavy traffic) against the background s = 0.5. The increase of the total at 20 kHz is computed below; it is ~0.001 dB.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = os.path.join(HERE, "..", "configs")


def psd(f, s, w):
    db = lambda x: 10 ** (x / 10.0)
    turb = 17.0 - 30.0 * math.log10(f)
    ship = 40.0 + 20.0 * (s - 0.5) + 26.0 * math.log10(f) - 60.0 * math.log10(f + 0.03)
    wind = 50.0 + 7.5 * math.sqrt(w) + 20.0 * math.log10(f) - 40.0 * math.log10(f + 0.4)
    therm = -15.0 + 20.0 * math.log10(f)
    return 10.0 * math.log10(db(turb) + db(ship) + db(wind) + db(therm))


S0, W0, FC = 0.5, 5.0, 20.0
RR = 10.0
spl5 = 42.4 + 15.4 * math.log10(RR)
b5 = psd(5.0, S0, W0)
rain = 10.0 * math.log10(1.0 + 10 ** ((spl5 - b5) / 10.0))
ship = psd(FC, 1.0, W0) - psd(FC, S0, W0)

print("background at 5 kHz %.2f dB, at 20 kHz %.2f dB" % (b5, psd(FC, S0, W0)))
print("rain %.0f mm/h: SPL5k = %.2f dB -> excess over background at 5 kHz %.2f dB (taken for the 20 kHz band)" % (RR, spl5, rain))
print("shipping s 0.5 -> 1.0 at 20 kHz: +%.4f dB" % ship)
for f in (10.0, 20.0, 30.0):
    print("  shipping s=1 vs s=0.5 at %.0f kHz: +%.4f dB" % (f, psd(f, 1.0, W0) - psd(f, S0, W0)))

scn = {
    "scn-burst.txt": ("Rain squall (literature: Ma & Nystuen 2005 rain-rate law, 10 mm/h; see doc/CONFIRM.md E46). Region: the central 2x2 cells in x,y and the\n"
                      "# upper 1500 m; 800-1400 s. Extent and duration are NOT from a retrieved source (CONFIRM E46).",
                      {"NoiseBandOffsetDb": round(rain, 1), "NoiseBandXMinM": 750, "NoiseBandXMaxM": 2250, "NoiseBandYMinM": 750, "NoiseBandYMaxM": 2250,
                       "NoiseBandZMinM": 0, "NoiseBandZMaxM": 1500, "NoiseBandStartS": 800, "NoiseBandEndS": 1400}),
    "scn-shipping.txt": ("Shipping lane (literature: Stojanovic/Wenz shipping term, s 0.5 -> 1 at 20 kHz = %.4f dB, i.e. none; CONFIRM E46). Region: the western\n"
                         "# cell column, top cell layer, whole run." % ship,
                         {"NoiseBandOffsetDb": round(ship, 4), "NoiseBandXMinM": 0, "NoiseBandXMaxM": 750, "NoiseBandYMinM": -1e9, "NoiseBandYMaxM": 1e9,
                          "NoiseBandZMinM": 0, "NoiseBandZMaxM": 750, "NoiseBandStartS": 0, "NoiseBandEndS": -1}),
    "scn-col10.txt": ("The +10 dB column of 5 Nov 2026 (continuity): second cell column, all y and depths, whole run.",
                      {"NoiseBandOffsetDb": 10, "NoiseBandXMinM": 750, "NoiseBandXMaxM": 1500, "NoiseBandYMinM": -1e9, "NoiseBandYMaxM": 1e9,
                       "NoiseBandZMinM": -1e9, "NoiseBandZMaxM": 1e9, "NoiseBandStartS": 0, "NoiseBandEndS": -1}),
}
for name, (comment, kv) in scn.items():
    with open(os.path.join(CFG, name), "w") as f:
        f.write("# %s\n# Generated by scripts/noise_scenarios.py; frozen before any result was seen. Used together with g-base.txt.\n" % comment)
        for k, v in kv.items():
            f.write("%s = %s\n" % (k, v))
    print("wrote", name)
